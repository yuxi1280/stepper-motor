#ifndef __MAIN_H__
#define __MAIN_H__

#include "hc32_ll.h"

/* ============================================================================
 * 阻塞期服务回调
 * ----------------------------------------------------------------------------
 * 回零(最长 60s)、标定(数分钟)、舵机动作(2s)这些长阻塞期间, 主循环不跑,
 * CAN 收不到也回不了, 上位机看起来"设备死了"。
 * 这里提供一个回调钩子: can.c 在 can_init() 里注册一个"收 CAN + 跑串口任务"
 * 的函数, motor.c / lc.c 在自己的阻塞循环里每秒调几次 app_service() 即可。
 * ========================================================================== */
typedef void (*app_service_fn_t)(void);

void app_set_service(app_service_fn_t fn);   /* 注册服务函数(只能注册一个) */
void app_service(void);                      /* 调用已注册的服务函数(没注册则什么都不做) */

#endif /* __MAIN_H__ */

