#ifndef __MAIN_H__
#define __MAIN_H__

#include "hc32_ll.h"

/* ============================================================================
 * 阻塞期服务回调
 * ----------------------------------------------------------------------------
 * 回零(最长 60s)、标定(数分钟)、舵机动作(2s)这些长阻塞期间, 主循环不跑,
 * CAN 收不到也回不了, 上位机看起来"设备死了"。
 * 这里提供一个回调钩子: can.c 在 can_init() 里注册一个"收 CAN + 跑串口任务"
 * 的函数, motor.c / lc.c 在自己的阻塞循环里每秒调几次 app_service() 即可。
 * ========================================================================== */
typedef void (*app_service_fn_t)(void);

void app_set_service(app_service_fn_t fn);   
void app_service(void);                     

/* ============================================================================
 * 校准中止标志(急停/停止时置位)
 * ----------------------------------------------------------------------------
 * 主动校准的回零/扫描都是长阻塞循环, 急停(0x04/0x05/L3 故障)是保护底线,
 * 必须能真正停下。阻塞循环里每轮调 app_abort_active() 检查, 置位即提前退出。
 * ========================================================================== */
void    app_abort_calib(void);      /* 置位校准取消标志 */
void    app_abort_clear(void);      /* 清除标志(校准开始前调用) */
uint8_t app_abort_active(void);     /* 1=需要中止当前校准动作 */

#endif /* __MAIN_H__ */

